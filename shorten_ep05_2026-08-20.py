def spoken_chars(text: str) -> int:
    """TTS が実際に読む文字数。話者ラベル・[TRANSITION]・空白を除く。"""
    body = re.sub(r"^\s*\[[A-Z_]+\]\s*$", "", text, flags=re.M)
    body = re.sub(r"^Speaker \d+:\s*", "", body, flags=re.M)
    return len(re.sub(r"\s+", "", body))


def apply_cuts(text: str, cuts: list[Cut]) -> tuple[str, list[tuple[Cut, int]]]:
    report: list[tuple[Cut, int]] = []
    for cut in cuts:
        count = text.count(cut.old)
        if count != 1:
            raise SystemExit(f"{cut.cut_id}: 旧文字列が {count} 件（1件であるべき）— {cut.where}")
        before = spoken_chars(text)
        text = text.replace(cut.old, cut.new, 1)
        text = re.sub(r"\n{3,}", "\n\n", text)
        report.append((cut, before - spoken_chars(text)))
    return text, report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tiers", default="AB", help="適用する層（A / AB）。既定 AB")
    parser.add_argument("--apply", action="store_true", help="実際に script.txt を書き換える（承認後のみ）")
    args = parser.parse_args()

    if not SCRIPT.exists():
        raise SystemExit(f"台本が見つからない: {SCRIPT}")

    original = SCRIPT.read_text(encoding="utf-8")
    selected = [c for c in CUTS if c.tier in args.tiers]
    updated, report = apply_cuts(original, selected)

    before = spoken_chars(original)
    after = spoken_chars(updated)
    print(f"台本: {SCRIPT}")
    print(f"レート: {CHARS_PER_MIN} 文字/分（ep05 実測）+ BGM {BGM_OVERHEAD_MIN} 分\n")
    print(f"{'ID':<5} {'層':<3} {'箇所':<16} {'削減字':>7} {'秒':>6}")
    for cut, saved in report:
        print(f"{cut.cut_id:<5} {cut.tier:<3} {cut.where:<16} {saved:>7} {saved / CHARS_PER_MIN * 60:>6.0f}")

    saved_total = before - after
    dur_before = before / CHARS_PER_MIN + BGM_OVERHEAD_MIN
    dur_after = after / CHARS_PER_MIN + BGM_OVERHEAD_MIN
    print(f"\n発話文字: {before} → {after}（-{saved_total}）")
    print(f"予測尺（BGM込み）: {dur_before:.2f}分 → {dur_after:.2f}分（-{dur_before - dur_after:.2f}分）")
    print(f"30分まで: {'残り %.2f分' % (30 - dur_after) if dur_after < 30 else '超過'}")

    if not args.apply:
        print("\n[dry-run] 台本は変更していない。適用は --apply（user 承認後）。")
        return 0

    backup = SCRIPT.with_suffix(".txt.pre_shorten_20260820")
    shutil.copy2(SCRIPT, backup)
    SCRIPT.write_text(updated, encoding="utf-8")
    print(f"\n適用した。バックアップ: {backup}")
    print("次: /rerender-podcast で Ep005 を再レンダー（TTS_RANDOM_VOICE=0 "
          "TTS_HOST1_ID=1937616896 TTS_HOST2_ID=1138003200）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
